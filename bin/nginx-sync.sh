#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

if [ -f "${PROJECT_ROOT}/.env" ]; then
  # shellcheck disable=SC1091
  . "${PROJECT_ROOT}/bin/load-env.sh"
  load_dotenv "${PROJECT_ROOT}/.env"
fi

WEB_PORT="${NGINX_WEB_PORT:-${NGINX_APP_PORT:-12017}}"
PRIMARY_DOMAIN="${NGINX_DOMAIN:-${SITE_DOMAIN:-roosa.biz}}"
ACME_ROOT="${NGINX_ACME_ROOT:-/www/wwwroot/${PRIMARY_DOMAIN}/public}"
INCLUDE_AAPANEL_EXT="${NGINX_INCLUDE_AAPANEL_EXT:-0}"
REPLACE_SYSTEM_NGINX_CONF="${NGINX_REPLACE_SYSTEM_CONF:-1}"
SYSTEM_NGINX_CONF="${SYSTEM_NGINX_CONF:-/etc/nginx/nginx.conf}"
PANEL_VHOST_DIR="${PANEL_VHOST_DIR:-/www/server/panel/vhost/nginx}"
NGINX_BINARY="${NGINX_BIN:-/www/server/nginx/sbin/nginx}"
NGINX_CONF="${NGINX_CONF:-/www/server/nginx/conf/nginx.conf}"
CLOUDFLARE_IPS_CONF="${PANEL_VHOST_DIR}/cloudflare-ips.conf"

if [ ! -d "${PANEL_VHOST_DIR}" ]; then
  echo "nginx-sync: aaPanel vhost dir not found at ${PANEL_VHOST_DIR}; skipping."
  exit 0
fi

cert_ready() {
  local cert_dir="/www/server/panel/vhost/cert/$1"
  [ -f "${cert_dir}/fullchain.pem" ] && [ -f "${cert_dir}/privkey.pem" ]
}

write_cloudflare_ips() {
  cat > "${CLOUDFLARE_IPS_CONF}" <<'EOF'
# Auto-generated by bin/nginx-sync.sh
set_real_ip_from 173.245.48.0/20;
set_real_ip_from 103.21.244.0/22;
set_real_ip_from 103.22.200.0/22;
set_real_ip_from 103.31.4.0/22;
set_real_ip_from 141.101.64.0/18;
set_real_ip_from 108.162.192.0/18;
set_real_ip_from 190.93.240.0/20;
set_real_ip_from 188.114.96.0/20;
set_real_ip_from 197.234.240.0/22;
set_real_ip_from 198.41.128.0/17;
set_real_ip_from 162.158.0.0/15;
set_real_ip_from 104.16.0.0/13;
set_real_ip_from 104.24.0.0/14;
set_real_ip_from 172.64.0.0/13;
set_real_ip_from 2400:cb00::/32;
set_real_ip_from 2606:4700::/32;
set_real_ip_from 2803:f800::/32;
set_real_ip_from 2405:b500::/32;
set_real_ip_from 2405:8100::/32;
set_real_ip_from 2a06:98c0::/29;
set_real_ip_from 2c0f:f248::/32;
EOF
}

write_vhost() {
  local domain="$1" conf_path="${PANEL_VHOST_DIR}/$1.conf"
  if ! cert_ready "${domain}"; then
    echo "nginx-sync: missing cert for ${domain}; skipping vhost."
    return 0
  fi

  write_cloudflare_ips
  cat > "${conf_path}" <<EOF
# Auto-generated by bin/nginx-sync.sh
server {
    listen 80;
    listen [::]:80;
    server_name ${domain};
    location ^~ /.well-known/acme-challenge/ {
        root ${ACME_ROOT};
        try_files \$uri =404;
    }
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${domain};

    ssl_certificate /www/server/panel/vhost/cert/${domain}/fullchain.pem;
    ssl_certificate_key /www/server/panel/vhost/cert/${domain}/privkey.pem;
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

    real_ip_header CF-Connecting-IP;
    real_ip_recursive on;
    include ${CLOUDFLARE_IPS_CONF};

    location / {
        proxy_pass http://127.0.0.1:${WEB_PORT};
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Port 443;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$http_connection;
        proxy_buffering off;
        proxy_read_timeout 300s;
    }

    location ~ ^/(\.user\.ini|\.htaccess|\.git|\.env|\.svn|\.project|LICENSE|README\.md) {
        return 404;
    }
    location ^~ /.well-known/ { allow all; }
    access_log /www/wwwlogs/${domain}.log;
    error_log /www/wwwlogs/${domain}.error.log;
}
EOF
}

replace_system_nginx_conf_if_enabled() {
  local backup_path system_conf_dir
  [ "${REPLACE_SYSTEM_NGINX_CONF}" = "1" ] || return 0
  [ -f "${NGINX_CONF}" ] || { echo "nginx-sync: nginx conf not found at ${NGINX_CONF}; skipping system link."; return 0; }
  system_conf_dir="$(dirname "${SYSTEM_NGINX_CONF}")"
  mkdir -p "${system_conf_dir}"
  if [ -L "${SYSTEM_NGINX_CONF}" ] && [ "$(readlink "${SYSTEM_NGINX_CONF}")" = "${NGINX_CONF}" ]; then return 0; fi
  if [ -e "${SYSTEM_NGINX_CONF}" ] && [ ! -L "${SYSTEM_NGINX_CONF}" ]; then
    backup_path="${SYSTEM_NGINX_CONF}.bak.$(date +%Y%m%d%H%M%S)"
    cp -f "${SYSTEM_NGINX_CONF}" "${backup_path}"
    echo "nginx-sync: backup created at ${backup_path}"
  fi
  ln -sfn "${NGINX_CONF}" "${SYSTEM_NGINX_CONF}"
}

write_vhost "${PRIMARY_DOMAIN}"
replace_system_nginx_conf_if_enabled
echo "nginx-sync: primary=${PRIMARY_DOMAIN} web_port=${WEB_PORT}"

if [ -x "${NGINX_BINARY}" ]; then
  "${NGINX_BINARY}" -t -c "${NGINX_CONF}"
  "${NGINX_BINARY}" -s reload
else
  echo "nginx-sync: nginx binary not found at ${NGINX_BINARY}; skipping reload."
fi

